"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { prisma } from "@/lib/db";
import { requireUserWithBranch, requirePermission, requireWrite } from "@/lib/auth";
import { isOutsideBranch } from "@/lib/branch";
import { logAudit } from "@/lib/audit";
import { assertContactsValid } from "@/lib/validators";
import { ownBankId } from "@/lib/books/banks";
import { lockedPeriodError, markBooksStale } from "@/lib/books/lockCheck";
import { todayInUae } from "@/lib/today";

export async function markInvoicePaidAction(formData: FormData): Promise<{ error?: string }> {
  await requireWrite("billing.invoices");
  assertContactsValid(formData);
  const { user, branchId, isSuperAdmin } = await requireUserWithBranch();
  const invoiceId = String(formData.get("invoiceId") || "");
  if (!invoiceId) return {};

  const existing = await prisma.clientInvoice.findUnique({
    where: { id: invoiceId },
  });
  if (!existing || isOutsideBranch(existing.branchId, branchId, isSuperAdmin)) return {};

  const day = String(formData.get("paidDate") || "");
  if (day && !/^\d{4}-\d{2}-\d{2}$/.test(day)) return { error: "Enter the date the money arrived." };
  if (day && day > todayInUae()) return { error: "The money can't have arrived in the future." };
  const paidDate = day ? new Date(`${day}T00:00:00.000Z`) : new Date();
  { const locked = await lockedPeriodError(existing.branchId, paidDate); if (locked) return { error: locked }; }
  const paidBankId = await ownBankId(formData.get("bankId"), existing.branchId);
  const data = { status: "PAID", paidDate, paidBankId };
  await prisma.clientInvoice.update({ where: { id: invoiceId }, data });
  await markBooksStale(existing.branchId);

  await logAudit({
    entityType: "CLIENT_INVOICE",
    entityId: invoiceId,
    action: "UPDATE",
    before: existing as unknown as Record<string, unknown>,
    after: data,
    userId: user.id,
    userName: user.name,
    branchId,
  });

  revalidatePath("/invoices/history");
  return {};
}

export async function deleteInvoiceAction(formData: FormData) {
  await requireWrite("billing.invoices");
  assertContactsValid(formData);
  await requirePermission("billing.invoices", "delete");
  const { user, branchId, isSuperAdmin } = await requireUserWithBranch();
  const invoiceId = String(formData.get("invoiceId") || "");
  if (!invoiceId) return;

  const existing = await prisma.clientInvoice.findUnique({
    where: { id: invoiceId },
  });
  if (!existing || isOutsideBranch(existing.branchId, branchId, isSuperAdmin)) return;

  // An invoice the client has already seen is an external financial record —
  // it gets cancelled or credited, never quietly removed. Only a draft that
  // was generated by mistake can go.
  if (existing.status !== "DRAFT") {
    redirect(
      `/invoices/history?error=${encodeURIComponent(
        `Can't delete ${existing.invoiceNumber}: it's already ${existing.status.toLowerCase()}. Only draft invoices can be deleted.`
      )}`
    );
  }

  await prisma.clientInvoice.delete({ where: { id: invoiceId } });

  await logAudit({
    entityType: "CLIENT_INVOICE",
    entityId: invoiceId,
    action: "DELETE",
    before: existing as unknown as Record<string, unknown>,
    userId: user.id,
    userName: user.name,
    branchId,
  });

  revalidatePath("/invoices/history");
}
